def in_hull(pt, cloud):
    n = len(cloud)
    res = linprog(np.zeros(n), A_eq=np.vstack([cloud.T, np.ones(n)]), b_eq=np.concatenate([pt, [1]]),
                  bounds=[(0, None)] * n, method="highs")
    return res.status == 0


