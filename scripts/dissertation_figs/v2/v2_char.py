def socket_split(frame: pd.DataFrame, tk: str, base: str):
    fr = frame.copy()
    y = fr[f"y_{tk}"] + (fr.victim.map(lambda a: dused[(a, tk)]) * fr.s_V if base == "J" else 0.0)
    fr["y"] = y
    wide = fr.pivot_table(index=["victim", "other"], columns="s_V", values="y")
    out = []
    diffs = {}
    for a in APPS:
        sub = fr[fr.victim == a]
        w = wide.loc[a].dropna() if a in wide.index.get_level_values(0) else pd.DataFrame()
        d = (w[1] - w[0]).to_numpy() if len(w) else np.array([])
        diffs[a] = d
        if len(d) >= 2:
            h = stats.t.ppf(0.975, len(d) - 1) * d.std(ddof=1) / np.sqrt(len(d))
        else:
            h = np.nan
        out.append(dict(app=NAME[a], mean_s0=sub.loc[sub.s_V == 0, "y"].mean(), n_s0=int((sub.s_V == 0).sum()),
                        mean_s1=sub.loc[sub.s_V == 1, "y"].mean(), n_s1=int((sub.s_V == 1).sum()),
                        n_paired=len(d), paired_d=d.mean() if len(d) else np.nan, ci_lo=d.mean() - h,
                        ci_hi=d.mean() + h, s1_lower=int((d < 0).sum())))
    rng = np.random.default_rng(SEED)
    means = np.array([diffs[a].mean() for a in APPS if len(diffs[a])])
    boots = []
    keys = [a for a in APPS if len(diffs[a])]
    for _ in range(1000):
        pick = rng.choice(len(keys), len(keys), replace=True)
        boots.append(np.mean([diffs[keys[i]][rng.choice(len(diffs[keys[i]]), len(diffs[keys[i]]))].mean()
                              for i in pick]))
    allp = np.concatenate([diffs[a] for a in keys])
    pooled_ = dict(mean_of_app_means=means.mean(), lo=np.percentile(boots, 2.5), hi=np.percentile(boots, 97.5),
                   n_pairs=len(allp), s1_lower=int((allp < 0).sum()), median_pair=np.median(allp))
    return pd.DataFrame(out), pooled_


