p("### (c) Do panel responses track App-App behaviour? (n = 10 apps, Spearman, two-sided permutation p from 200,000 random permutations, seed 923)\n")


def spearman_exact(x, y):
    rho = stats.spearmanr(x, y).statistic
    # 10! = 3.6M permutations: use 200,000 random permutations (seed 923) for the two-sided p
    rng = np.random.default_rng(SEED)
    rx, ry = stats.rankdata(x), stats.rankdata(y)
    perm = np.array([np.corrcoef(rx, ry[rng.permutation(len(ry))])[0, 1] for _ in range(200000)])
    return rho, (np.abs(perm) >= abs(rho) - 1e-12).mean()


